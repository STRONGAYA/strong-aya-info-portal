# HTML: a small tree with source offsets, so that a page is rewritten by
# replacing source spans and everything else stays byte-identical
# ------------------------------------------------------------------

class Node:
    """An element: its tag, attributes, the offsets of its start tag, inner HTML and end, and its children."""

    __slots__ = ('tag', 'attrs', 'tag_text', 'start', 'inner_start', 'inner_end', 'end', 'children', 'parent')

    def __init__(self, tag, attrs, tag_text, start, parent):
        self.tag = tag
        self.attrs = attrs
        self.tag_text = tag_text
        self.start = start
        self.inner_start = start + len(tag_text)
        self.inner_end = self.end = self.inner_start
        self.children = []
        self.parent = parent

    def classes(self):
        return (self.attrs.get('class') or '').split()

    def attribute_span(self, name):
        """(start, end, raw value) of the attribute's value in the source, or None (first occurrence)."""
        for match in TAG_ATTRIBUTE.finditer(self.tag_text):
            if match.group(1).lower() != name:
                continue
            for group in (2, 3, 4):
                if match.group(group) is not None:
                    return self.start + match.start(group), self.start + match.end(group), match.group(group)
        return None


class Text:
    __slots__ = ('start', 'text', 'parent')

    def __init__(self, start, text, parent):
        self.start = start
        self.text = text
        self.parent = parent


class PageParser(HTMLParser):
    """Build the element tree of a page with source offsets (html.parser reports line and column per token)."""

    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.source = source
        self.line_starts = [0] + [m.end() for m in re.finditer('\n', source)]
        self.root = Node('#root', {}, '', 0, None)
        self.root.inner_end = self.root.end = len(source)
        self.stack = [self.root]

    def source_offset(self):
        line, column = self.getpos()
        return self.line_starts[line - 1] + column

    def _open(self, tag, attrs, void):
        node = Node(tag, dict(attrs), self.get_starttag_text(), self.source_offset(), self.stack[-1])
        self.stack[-1].children.append(node)
        if not void:
            self.stack.append(node)

    def handle_starttag(self, tag, attrs):
        self._open(tag, attrs, tag in VOID_TAGS)

    def handle_startendtag(self, tag, attrs):
        self._open(tag, attrs, True)

    def handle_endtag(self, tag):
        position = self.source_offset()
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i].tag != tag:
                continue
            # Elements left open inside it (sloppy HTML) end where it ends
            for node in self.stack[i + 1:]:
                node.inner_end = node.end = position
            node = self.stack[i]
            node.inner_end = position
            match = re.compile(r'</\s*%s\s*>' % re.escape(tag), re.IGNORECASE).match(self.source, position)
            node.end = match.end() if match else position
            del self.stack[i:]
            return

    def handle_data(self, data):
        self.stack[-1].children.append(Text(self.source_offset(), data, self.stack[-1]))

    def close(self):
        super().close()
        for node in self.stack[1:]:
            node.inner_end = node.end = len(self.source)
        del self.stack[1:]


def parse_html(source):
    parser = PageParser(source)
    parser.feed(source)
    parser.close()
    return parser.root


def is_skipped(node):
    """Content that is never translated: scripts, translate="no", text in another language, generated notice."""
    if node.tag in SKIP_TAGS:
        return True
    if (node.attrs.get('translate') or '').strip().lower() == 'no':
        return True
    classes = node.classes()
    if 'notranslate' in classes or 'translation-notice' in classes:
        return True
    lang = node.attrs.get('lang')
    if lang and node.tag != 'html' and lang.split('-')[0].lower() != 'en':
        return True
    return False


def in_notice(node):
    """Is the element inside the generated translation notice (whose link to the English page is no page link)?"""
    while node is not None:
        if 'translation-notice' in node.classes():
            return True
        node = node.parent
    return False


def has_letters(text):
    return bool(LETTER.search(text))


def direct_letters(node):
    return any(isinstance(child, Text) and has_letters(child.text) for child in node.children)


def subtree_letters(node):
    for child in node.children:
        if isinstance(child, Text):
            if has_letters(child.text):
                return True
        elif not is_skipped(child) and subtree_letters(child):
            return True
    return False


def find_node(node, tag):
    for child in node.children:
        if isinstance(child, Node):
            if child.tag == tag:
                return child
            found = find_node(child, tag)
            if found:
                return found
    return None


class Unit:
    """A translation unit: the inner HTML of an element (kind 'html'), an attribute value (kind 'attr')
    or a string of the strings file (kind 'string'). inside is the unit element it sits in, if any."""

    def __init__(self, kind, source, node=None, attr=None, span=None, inside=None, path=None):
        self.kind = kind
        self.source = source
        self.key = sha256(source)
        self.node = node
        self.attr = attr
        self.span = span  # (start, end, raw) of an attribute value in the page source
        self.inside = inside
        self.path = path  # key path in the strings file


class PathAttribute:
    """An href/src attribute that points to a shared asset and gets one more ../ in a translated tree."""

    def __init__(self, node, attr, value, span, inside):
        self.node = node
        self.attr = attr
        self.value = value
        self.span = span
        self.inside = inside


class Page:
    """One English page: its translation units, attribute units, asset paths and links to other pages."""

    def __init__(self, path, rel, source=None):
        self.path = path
        self.rel = rel  # e.g. 'module_a/chemotherapy.html'
        self.depth = rel.count('/')
        self.source = read_text(path) if source is None else source
        self.units = []
        self.attr_units = []
        self.path_attrs = []
        self.links = set()
        root = parse_html(self.source)
        self.html_node = find_node(root, 'html')
        self._walk(root, None, False)

    def _walk(self, node, in_unit, skipped):
        for child in node.children:
            if not isinstance(child, Node):
                continue
            child_skipped = skipped or is_skipped(child)
            self._note_paths(child, in_unit)
            if child_skipped:
                self._walk(child, in_unit, True)
                continue
            for attr in TRANSLATED_ATTRIBUTES:
                self._note_attribute(child, attr, in_unit)
            if child.tag == 'meta' and (child.attrs.get('name') or '').lower() == 'description':
                self._note_attribute(child, 'content', in_unit)
            if in_unit is not None:
                self._walk(child, in_unit, False)
            elif child.tag in BLOCK_UNITS and subtree_letters(child):
                self._add_unit(child)
            elif child.tag in INLINE_CANDIDATES and direct_letters(child):
                self._add_unit(child)
            else:
                self._walk(child, None, False)

    def _add_unit(self, node):
        source = normalise(self.source[node.inner_start:node.inner_end])
        self.units.append(Unit('html', source, node=node))
        self._walk(node, node, False)

    def _note_attribute(self, node, attr, in_unit):
        value = node.attrs.get(attr)
        if not value or not has_letters(value):
            return
        span = node.attribute_span(attr)
        if span is None:
            return
        self.attr_units.append(Unit('attr', normalise(value), node=node, attr=attr, span=span, inside=in_unit))

    def _note_paths(self, node, in_unit):
        for attr in ('href', 'src'):
            value = node.attrs.get(attr)
            if value is None:
                continue
            if ASSET_PATH.match(value):
                span = node.attribute_span(attr)
                if span is not None:
                    self.path_attrs.append(PathAttribute(node, attr, value, span, in_unit))
            elif attr == 'href' and value and not ABSOLUTE_URL.match(value) and not value.startswith('#') \
                    and not in_notice(node):
                self.links.add(value)

    def english_url(self, base_url):
        return base_url + self.rel


class Strings:
    """The strings file (web/i18n/en.js): strict JSON after 'window.AYA_STRINGS =', one unit per string."""

    def __init__(self, path):
        self.path = path
        self.text = read_text(path)
        match = STRINGS_PREFIX.search(self.text)
        if not match:
            raise ValueError('%s: no "window.AYA_STRINGS = " line' % path)
        self.data = json.loads(self.text[match.end():].strip().rstrip(';'), object_pairs_hook=OrderedDict)
        self.leaves = []
        self._collect(self.data, [])

    def _collect(self, node, path):
        if isinstance(node, dict):
            for key, value in node.items():
                self._collect(value, path + [key])
        elif isinstance(node, list):
            for i, value in enumerate(node):
                self._collect(value, path + [str(i)])
        elif isinstance(node, str):
            self.leaves.append(Unit('string', node, path='.'.join(path)))

    def render(self, lang, translate, national_descriptions=None):
        """The strings file of a language: the same structure with every string replaced by translate(string),
        plus the translated descriptions of the national websites under national.descriptions."""

        def convert(node):
            if isinstance(node, dict):
                return OrderedDict((key, convert(value)) for key, value in node.items())
            if isinstance(node, list):
                return [convert(value) for value in node]
            if isinstance(node, str):
                return translate(node)
            return node

        data = convert(self.data)
        if national_descriptions:
            data.setdefault('national', OrderedDict())['descriptions'] = national_descriptions
        return (STRINGS_HEADER % lang) + 'window.AYA_STRINGS = ' + \
            json.dumps(data, indent=2, ensure_ascii=False) + ';\n'


