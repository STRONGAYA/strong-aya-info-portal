def log(message):
    print(message, flush=True)


def sha256(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def normalise(text):
    """Whitespace (indentation, line breaks) does not matter in HTML: one space, no edges."""
    return re.sub(r'\s+', ' ', text).strip()


def escape_attribute(value):
    return value.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')


def wrap_placeholders(text):
    """Protect {name} placeholders of the strings file from translation (DeepL honours translate="no")."""
    return PLACEHOLDER.sub(lambda m: '<span translate="no">' + m.group(0) + '</span>', text)


def unwrap_placeholders(text):
    return re.sub(r'<span translate="no">(\{\w+\})</span>', r'\1', text)


def missing_placeholders(source, target):
    return sorted(set(PLACEHOLDER.findall(source)) - set(PLACEHOLDER.findall(target)))


def read_text(path):
    with open(path, 'r', encoding='utf-8', newline='') as f:
        return f.read()


def write_text(path, text):
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(text)


