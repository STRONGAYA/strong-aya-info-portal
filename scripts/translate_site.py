class Cache:
    """translations/<lang>.json: one entry per English text (key = sha256), with the translation and its
    status: 'machine' (from DeepL) or 'reviewed' (a person approved or corrected it; never overwritten)."""

    def __init__(self, path):
        self.path = path
        self.exists = os.path.exists(path)
        self.entries = OrderedDict()
        if self.exists:
            with open(path, 'r', encoding='utf-8') as f:
                self.entries = json.load(f, object_pairs_hook=OrderedDict)

    def target(self, key):
        entry = self.entries.get(key)
        return entry['target'] if entry else None

    def status(self, key):
        entry = self.entries.get(key)
        return entry['status'] if entry else None

    def set_machine(self, key, source, target, billed, glossary, engine):
        """Store a machine translation; a reviewed entry is never overwritten."""
        if self.status(key) == 'reviewed':
            return False
        self.entries[key] = OrderedDict([
            ('source', source), ('target', target), ('status', 'machine'), ('engine', engine),
            ('glossary', glossary), ('billed', billed), ('date', datetime.date.today().isoformat()),
            ('reviewer', '')
        ])
        return True

    def save(self):
        os.makedirs(os.path.dirname(self.path) or '.', exist_ok=True)
        with open(self.path, 'w', encoding='utf-8') as f:
            json.dump(self.entries, f, indent=2, ensure_ascii=False)
            f.write('\n')
        self.exists = True


