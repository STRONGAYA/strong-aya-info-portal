class DeepLError(RuntimeError):
    pass


class DeepLClient:
    def __init__(self, key):
        self.key = key
        # A key of the free plan ends in ":fx" and talks to another host
        self.host = 'api-free.deepl.com' if key.endswith(':fx') else 'api.deepl.com'

    def request(self, method, path, body=None):
        """One API call, with back-off on 429 and server errors; quota and request errors are fatal."""
        data = json.dumps(body).encode('utf-8') if body is not None else None
        for attempt in range(1, MAX_ATTEMPTS + 1):
            request = urllib.request.Request('https://%s%s' % (self.host, path), data=data, method=method, headers={
                'Authorization': 'DeepL-Auth-Key ' + self.key,
                'Content-Type': 'application/json',
                'User-Agent': USER_AGENT
            })
            try:
                with urllib.request.urlopen(request, timeout=120) as response:
                    payload = response.read().decode('utf-8')
                    return json.loads(payload) if payload.strip() else {}
            except urllib.error.HTTPError as error:
                message = error.read().decode('utf-8', 'replace')[:500]
                if error.code == 456:
                    raise DeepLError('DeepL: the character quota of this plan is exhausted (456): ' + message)
                if error.code in RETRY_STATUSES and attempt < MAX_ATTEMPTS:
                    wait = 2 ** attempt
                    log('DeepL answered %s; waiting %s s before trying again' % (error.code, wait))
                    time.sleep(wait)
                    continue
                raise DeepLError('DeepL: %s %s failed with %s: %s' % (method, path, error.code, message))
            except urllib.error.URLError as error:
                if attempt < MAX_ATTEMPTS:
                    time.sleep(2 ** attempt)
                    continue
                raise DeepLError('DeepL: %s %s failed: %s' % (method, path, error))

    def translate(self, texts, target_lang, parameters):
        body = OrderedDict([('text', texts), ('source_lang', 'EN'), ('target_lang', target_lang)])
        body.update(parameters)
        answer = self.request('POST', TRANSLATE_PATH, body)
        translations = answer.get('translations') or []
        if len(translations) != len(texts):
            raise DeepLError('DeepL returned %d translations for %d texts' % (len(translations), len(texts)))
        return [(t.get('text', ''), int(t.get('billed_characters') or 0)) for t in translations]

    def usage(self):
        return self.request('GET', USAGE_PATH)

    def create_glossary(self, name, dictionaries):
        return self.request('POST', GLOSSARY_PATH, {'name': name, 'dictionaries': dictionaries})

    def replace_dictionary(self, glossary_id, dictionary):
        return self.request('PUT', '%s/%s/dictionaries' % (GLOSSARY_PATH, glossary_id), dictionary)


