class Site:
    def __init__(self, web_dir, translations_dir):
        self.web_dir = web_dir
        self.translations_dir = translations_dir
        self.config = self._load_config()
        self.pages = [Page(os.path.join(web_dir, rel), rel) for rel in self._page_paths()]
        self.strings = Strings(os.path.join(web_dir, 'i18n', 'en.js'))
        self.national_units = self._national_units(os.path.join(web_dir, 'data', 'national_resources.json'))
        # Every unit once: the same text on 17 pages is one entry
        self.units = OrderedDict()
        for page in self.pages:
            for unit in page.units + page.attr_units:
                self.units.setdefault(unit.key, unit)
        for unit in self.strings.leaves + self.national_units:
            self.units.setdefault(unit.key, unit)
        self.glossary_path = os.path.join(translations_dir, 'glossary.tsv')
        self.glossary_header, self.glossary_rows = load_glossary(self.glossary_path)
        self.glossary_info = self._load_json(os.path.join(translations_dir, 'glossary.json')) or {}
        self.caches = {}

    def _load_config(self):
        config = json.loads(json.dumps(DEFAULT_CONFIG))
        loaded = self._load_json(os.path.join(self.translations_dir, 'config.json')) or {}
        for key, value in loaded.items():
            if isinstance(value, dict) and isinstance(config.get(key), dict):
                config[key].update(value)
            else:
                config[key] = value
        return config

    def _national_units(self, path):
        """The English one-sentence descriptions of the national websites, one unit per website, keyed by
        country code and position in the country's list (portal.js looks them up the same way)."""
        data = self._load_json(path) or {}
        units = []
        for code, entry in (data.get('countries') or {}).items():
            for index, resource in enumerate(entry.get('resources') or []):
                description = normalise(str(resource.get('description') or ''))
                if has_letters(description):
                    units.append(Unit('string', description, path='national.descriptions.%s/%d' % (code, index)))
        return units

    @staticmethod
    def _load_json(path):
        if not os.path.exists(path):
            return None
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)

    def _page_paths(self):
        paths = sorted(name for name in os.listdir(self.web_dir) if name.endswith('.html'))
        for directory in sorted(os.listdir(self.web_dir)):
            if directory.startswith('module_') and os.path.isdir(os.path.join(self.web_dir, directory)):
                paths += [directory + '/' + name for name in sorted(os.listdir(os.path.join(self.web_dir, directory)))
                          if name.endswith('.html')]
        return paths

    # --- languages ---

    def cached_languages(self):
        """The languages that have a cache file: that is what enables a language."""
        if not os.path.isdir(self.translations_dir):
            return []
        return sorted(name[:-5] for name in os.listdir(self.translations_dir)
                      if name.endswith('.json') and re.fullmatch(r'[a-z]{2,3}', name[:-5]))

    def cache(self, lang):
        if lang not in self.caches:
            self.caches[lang] = Cache(os.path.join(self.translations_dir, lang + '.json'))
        return self.caches[lang]

    def html_lang(self, lang):
        return self.config['html_lang'].get(lang, lang)

    def deepl_target(self, lang):
        return self.config['deepl_targets'].get(lang, lang.upper())

    def native_name(self, lang):
        return NATIVE_NAMES.get(lang, lang)

    def tree_dir(self, lang):
        return os.path.join(self.web_dir, lang)

    def tree_complete(self, lang):
        """Does the full page tree of the language exist on disk?"""
        return all(os.path.exists(os.path.join(self.tree_dir(lang), page.rel)) for page in self.pages) and \
            os.path.exists(os.path.join(self.web_dir, 'i18n', lang + '.js'))

    def listed_languages(self):
        """The languages the portal is available in: a cache and a complete tree."""
        return [lang for lang in self.cached_languages() if self.tree_complete(lang)]

    def language_status(self, lang):
        cache = self.cache(lang)
        return 'reviewed' if all(cache.status(key) == 'reviewed' for key in self.units) else 'machine'

    # --- misses ---

    def misses(self, lang, retranslate_glossary=False):
        cache = self.cache(lang)
        current = self.glossary_version_for(lang)
        missing = []
        for key, unit in self.units.items():
            status = cache.status(key)
            if status is None:
                missing.append(unit)
            elif retranslate_glossary and status == 'machine' and cache.entries[key].get('glossary') != current:
                missing.append(unit)
        return missing

    def page_misses(self, page, lang):
        cache = self.cache(lang)
        return [unit for unit in page.units + page.attr_units if cache.status(unit.key) is None]

    def strings_misses(self, lang):
        cache = self.cache(lang)
        return [unit for unit in self.strings.leaves + self.national_units if cache.status(unit.key) is None]

    # --- glossary ---

    def glossary_applies(self, lang):
        return (lang not in self.config['no_glossary_languages'] and
                bool(glossary_entries(self.glossary_header, self.glossary_rows, lang)))

    def glossary_version_for(self, lang):
        return self.glossary_info.get('version') if self.glossary_applies(lang) and self.glossary_info.get('id') else None

    # --- rendering ---

    def hreflang_lines(self, page, languages):
        base = self.config['base_url']
        lines = [('x-default', base + page.rel), ('en', base + page.rel)]
        lines += [(self.html_lang(lang), base + lang + '/' + page.rel) for lang in languages]
        return ''.join('    <link rel="alternate" hreflang="%s" href="%s"/>\n' % (tag, url) for tag, url in lines)

    def with_hreflang(self, text, page, languages):
        lines = self.hreflang_lines(page, languages)
        new_text, count = HREFLANG_BLOCK.subn(lambda m: m.group(1) + lines + m.group(3), text, count=1)
        if count == 0:
            log('warning: %s has no hreflang block' % page.rel)
        return new_text

    def render_page(self, page, lang, languages):
        """The page in a language, from the English source with the units, attributes, paths, html tag,
        hreflang block, notice and a 'generated' comment replaced; raises ValueError when a unit is missing."""
        cache = self.cache(lang)
        edits = []
        inner_subs = {}

        def target_of(unit):
            target = cache.target(unit.key)
            if target is None:
                raise ValueError('%s: no %s translation of %r' % (page.rel, lang, unit.source[:60]))
            return target

        for unit in page.attr_units:
            new_raw = escape_attribute(target_of(unit))
            if unit.inside is not None:
                inner_subs.setdefault(id(unit.inside), []).append((unit.attr, unit.span[2], new_raw))
            else:
                edits.append((unit.span[0], unit.span[1], new_raw))
        for path_attr in page.path_attrs:
            new_raw = escape_attribute(self.rewrite_path(path_attr.value, lang))
            if path_attr.inside is not None:
                inner_subs.setdefault(id(path_attr.inside), []).append((path_attr.attr, path_attr.span[2], new_raw))
            else:
                edits.append((path_attr.span[0], path_attr.span[1], new_raw))
        for unit in page.units:
            target = target_of(unit)
            for attr, old_raw, new_raw in inner_subs.get(id(unit.node), []):
                pattern = re.compile(r'(\s%s\s*=\s*")%s(")' % (re.escape(attr), re.escape(old_raw)))
                target, count = pattern.subn(lambda m: m.group(1) + new_raw + m.group(2), target, count=1)
                if count == 0:
                    log('warning: %s (%s): %s="%s" was changed by the translation itself, kept as returned'
                        % (page.rel, lang, attr, old_raw))
            edits.append((unit.node.inner_start, unit.node.inner_end, target))

        html_node = page.html_node
        status = self.page_status(page, lang)
        if html_node is not None:
            edits.append((html_node.start, html_node.inner_start, self.html_tag(html_node, page, lang, status)))

        text = apply_edits(page.source, edits)
        comment = ('<!-- Generated by scripts/translate_site.py from web/%s (DeepL); do not edit: edit the '
                   'English page or translations/%s.json -->\n' % (page.rel, lang))
        if text.startswith('<!DOCTYPE html>\n'):
            text = text.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + comment, 1)
        else:
            text = comment + text
        text = self.with_hreflang(text, page, languages)
        notice = self.notice_html(page, lang, status)
        if NOTICE_PLACEHOLDER in text:
            text = text.replace(NOTICE_PLACEHOLDER, notice, 1)
        else:
            log('warning: %s has no translation-notice placeholder' % page.rel)
        return text

    def html_tag(self, node, page, lang, status):
        tag = node.tag_text
        tag, count = re.subn(r'\slang="[^"]*"', ' lang="%s"' % self.html_lang(lang), tag, count=1)
        if count == 0:
            tag = tag.replace('<html', '<html lang="%s"' % self.html_lang(lang), 1)
        root = '../' * (page.depth + 1)
        tag, count = re.subn(r'\sdata-site-root="[^"]*"', ' data-site-root="%s"' % root, tag, count=1)
        if count == 0:
            tag = tag[:-1] + ' data-site-root="%s">' % root
        tag = re.sub(r'\sdata-translation="[^"]*"', '', tag)
        return tag[:-1] + ' data-translation="%s">' % status

    def page_status(self, page, lang):
        cache = self.cache(lang)
        units = page.units + page.attr_units
        return 'reviewed' if units and all(cache.status(unit.key) == 'reviewed' for unit in units) else 'machine'

    @staticmethod
    def rewrite_path(value, lang):
        value = '../' + value
        if value.endswith('i18n/en.js'):
            value = value[:-len('en.js')] + lang + '.js'
        return value

    def string_target(self, lang, path):
        """The translation of a string of the strings file by its key path, e.g. 'language.noticeEnglish'."""
        cache = self.cache(lang)
        for unit in self.strings.leaves:
            if unit.path == path:
                target = cache.target(unit.key)
                return target if target is not None else unit.source
        return path

    def notice_html(self, page, lang, status):
        settings = self.config['languages'].get(lang, {})
        if status == 'reviewed' and settings.get('reviewer') and settings.get('reviewed'):
            text = self.string_target(lang, 'language.noticeReviewed')
            text = text.replace('{reviewer}', settings['reviewer']).replace('{month}', settings['reviewed'])
        else:
            if status == 'reviewed':
                log('warning: %s is reviewed but translations/config.json has no reviewer/reviewed for %s'
                    % (lang, lang))
            text = self.string_target(lang, 'language.noticeMachine')
        english = '../' * (page.depth + 1) + page.rel
        return ('<div class="translation-notice" role="note"><span>%s</span> <a href="%s">%s</a></div>'
                % (text, english, self.string_target(lang, 'language.noticeEnglish')))

    def render_strings(self, lang):
        cache = self.cache(lang)

        def translate(source):
            target = cache.target(sha256(source))
            if target is None:
                raise ValueError('no %s translation of the string %r' % (lang, source[:60]))
            return target

        descriptions = OrderedDict((unit.path.split('.')[-1], translate(unit.source)) for unit in self.national_units)
        return self.strings.render(lang, translate, descriptions)

    def render_languages_js(self, languages):
        entries = [OrderedDict([('code', 'en'), ('name', 'English'), ('status', 'source')])]
        for lang in languages:
            entries.append(OrderedDict([('code', lang), ('name', self.native_name(lang)),
                                        ('status', self.language_status(lang))]))
        lines = ',\n'.join('  ' + json.dumps(entry, ensure_ascii=False) for entry in entries)
        return LANGUAGES_HEADER + 'window.AYA_LANGUAGES = [\n' + lines + '\n];\n'

    def validate_page(self, page, lang, text):
        """The generated page must have the same units, attributes and page links as the English one."""
        generated = Page(page.path, page.rel, source=text)
        problems = []
        if len(generated.units) != len(page.units):
            problems.append('%d units instead of %d' % (len(generated.units), len(page.units)))
        if len(generated.attr_units) != len(page.attr_units):
            problems.append('%d translated attributes instead of %d'
                            % (len(generated.attr_units), len(page.attr_units)))
        if generated.links != page.links:
            problems.append('page links differ: %s' % sorted(generated.links ^ page.links))
        if problems:
            raise ValueError('%s (%s): the generated page is not sound: %s' % (page.rel, lang, '; '.join(problems)))
        cache = self.cache(lang)
        for unit in page.units + page.attr_units:
            if cache.target(unit.key) == unit.source and has_letters(unit.source):
                log('note: %s (%s): left in English: %r' % (page.rel, lang, unit.source[:60]))

    # --- writing ---

    def write_tree(self, lang, languages):
        for page in self.pages:
            text = self.render_page(page, lang, languages)
            self.validate_page(page, lang, text)
            write_if_changed(os.path.join(self.tree_dir(lang), page.rel), text)
        write_if_changed(os.path.join(self.web_dir, 'i18n', lang + '.js'), self.render_strings(lang))

    def write_shared(self, languages):
        """The English pages' hreflang blocks and languages.js, for the languages that are available."""
        for page in self.pages:
            write_if_changed(page.path, self.with_hreflang(page.source, page, languages))
        write_if_changed(os.path.join(self.web_dir, 'i18n', 'languages.js'), self.render_languages_js(languages))

    # --- translating ---

    def translate(self, lang, client, units):
        """Translate the units with DeepL in batches, storing every answer in the cache at once."""
        cache = self.cache(lang)
        # Inline markup (<b>, links, the hidden "opens in a new tab" spans) travels inside the text: DeepL keeps
        # the tags, does not bill them and honours translate="no"
        parameters = OrderedDict([('tag_handling', 'html')])
        parameters.update(self.config['deepl_parameters'])
        if self.config.get('custom_instructions'):
            parameters['custom_instructions'] = list(self.config['custom_instructions'])
        glossary = self.glossary_version_for(lang)
        if glossary:
            parameters['glossary_id'] = self.glossary_info['id']
            if glossary != glossary_version(self.glossary_path):
                log('warning: translations/glossary.tsv changed since --sync-glossary; run it again first')
        if lang in self.config['beta_languages']:
            parameters['enable_beta_languages'] = True
        engine = 'deepl/' + str(parameters.get('model_type', 'default'))
        billed_total = 0
        for batch in batches(units):
            texts = [wrap_placeholders(unit.source) for unit in batch]
            results = client.translate(texts, self.deepl_target(lang), parameters)
            for unit, (text, billed) in zip(batch, results):
                target = unwrap_placeholders(text)
                missing = missing_placeholders(unit.source, target)
                if missing:
                    log('warning: %s: placeholders %s missing in the translation of %r: check translations/%s.json'
                        % (lang, missing, unit.source[:60], lang))
                cache.set_machine(unit.key, unit.source, target, billed, glossary, engine)
                billed_total += billed
            cache.save()
            log('%s: translated %d units (%d characters billed so far)' % (lang, len(batch), billed_total))
        return billed_total

    def sync_glossary(self, client):
        version = glossary_version(self.glossary_path)
        if version is None:
            raise ValueError('no %s' % self.glossary_path)
        languages = [lang for lang in self.glossary_header if lang not in ('en', '*')]
        dictionaries = []
        for lang in languages:
            pairs = glossary_entries(self.glossary_header, self.glossary_rows, lang)
            if pairs:
                dictionaries.append({'source_lang': 'en', 'target_lang': lang,
                                     'entries': '\n'.join('%s\t%s' % pair for pair in pairs), 'entries_format': 'tsv'})
        if not dictionaries:
            raise ValueError('translations/glossary.tsv has no complete entries for any language')
        name = self.glossary_info.get('name') or 'strong-aya-info-portal'
        glossary_id = self.glossary_info.get('id')
        if glossary_id:
            try:
                for dictionary in dictionaries:
                    client.replace_dictionary(glossary_id, dictionary)
            except DeepLError as error:
                if '404' not in str(error):
                    raise
                log('glossary %s no longer exists at DeepL; creating it anew' % glossary_id)
                glossary_id = None
        if not glossary_id:
            answer = client.create_glossary(name, dictionaries)
            glossary_id = answer.get('glossary_id')
            if not glossary_id:
                raise DeepLError('DeepL did not return a glossary_id: %s' % json.dumps(answer)[:300])
        self.glossary_info = OrderedDict([('id', glossary_id), ('name', name), ('version', version),
                                          ('languages', [d['target_lang'] for d in dictionaries]),
                                          ('date', datetime.date.today().isoformat())])
        with open(os.path.join(self.translations_dir, 'glossary.json'), 'w', encoding='utf-8') as f:
            json.dump(self.glossary_info, f, indent=2, ensure_ascii=False)
            f.write('\n')
        log('glossary %s: %d languages, version %s' % (glossary_id, len(dictionaries), version))

    # --- review ---

    def export_review(self, lang):
        cache = self.cache(lang)
        path = os.path.join(self.translations_dir, 'review', lang + '.csv')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(['key', 'status', 'source', 'target', 'reviewer'])
            for key, entry in cache.entries.items():
                writer.writerow([key, entry['status'], entry['source'], entry['target'], entry.get('reviewer', '')])
        log('%d entries written to %s' % (len(cache.entries), path))
        return path

    def import_review(self, lang):
        cache = self.cache(lang)
        path = os.path.join(self.translations_dir, 'review', lang + '.csv')
        changed = 0
        with open(path, 'r', encoding='utf-8', newline='') as f:
            for row in csv.DictReader(f):
                entry = cache.entries.get(row.get('key', ''))
                if entry is None:
                    log('warning: unknown key %s in %s is ignored' % (row.get('key'), path))
                    continue
                status = (row.get('status') or '').strip()
                if status not in ('machine', 'reviewed'):
                    raise ValueError('%s: the status of %s must be machine or reviewed, not %r' % (path, row['key'], status))
                target = row.get('target') or ''
                reviewer = (row.get('reviewer') or '').strip()
                if (entry['target'], entry['status'], entry.get('reviewer', '')) != (target, status, reviewer):
                    entry['target'], entry['status'], entry['reviewer'] = target, status, reviewer
                    if status == 'reviewed':
                        entry['date'] = datetime.date.today().isoformat()
                    changed += 1
        cache.save()
        log('%d entries updated from %s' % (changed, path))
        return changed

    def prune(self, lang):
        cache = self.cache(lang)
        orphans = [key for key in cache.entries if key not in self.units]
        for key in orphans:
            log('%s: dropping %r' % (lang, cache.entries[key]['source'][:70]))
            del cache.entries[key]
        if orphans:
            cache.save()
        log('%s: %d orphaned entries removed' % (lang, len(orphans)))
        return orphans


def apply_edits(source, edits):
    """Replace (start, end, text) spans of the source, back to front; the spans must not overlap."""
    result = source
    previous_start = len(source) + 1
    for start, end, text in sorted(edits, key=lambda edit: (edit[0], edit[1]), reverse=True):
        if end > previous_start:
            raise ValueError('overlapping edits at %d-%d' % (start, end))
        result = result[:start] + text + result[end:]
        previous_start = start
    return result


def batches(units):
    """Batches of at most MAX_TEXTS_PER_REQUEST units and MAX_BYTES_PER_REQUEST bytes of text."""
    batch, size = [], 0
    for unit in units:
        length = len(wrap_placeholders(unit.source).encode('utf-8')) + 16
        if batch and (len(batch) >= MAX_TEXTS_PER_REQUEST or size + length > MAX_BYTES_PER_REQUEST):
            yield batch
            batch, size = [], 0
        batch.append(unit)
        size += length
    if batch:
        yield batch


def write_if_changed(path, text):
    if os.path.exists(path) and read_text(path) == text:
        return False
    write_text(path, text)
    return True


