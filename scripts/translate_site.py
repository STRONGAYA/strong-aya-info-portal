def parse_languages(value):
    languages = [code.strip().lower() for code in (value or '').split(',') if code.strip()]
    for code in languages:
        if not re.fullmatch(r'[a-z]{2,3}', code) or code == 'en':
            raise SystemExit('--languages: %r is not a language code (two or three letters, not en)' % code)
    return languages


def check(site):
    """Compare what the cache produces with what is on disk; 1 when a generated file differs or is missing."""
    problems = []
    languages = site.listed_languages()
    for lang in site.cached_languages():
        for page in site.pages:
            path = os.path.join(site.tree_dir(lang), page.rel)
            misses = site.page_misses(page, lang)
            if misses:
                log('stale: %s/%s has %d untranslated units' % (lang, page.rel, len(misses)))
                continue
            expected = site.render_page(page, lang, languages)
            if not os.path.exists(path):
                problems.append('%s: missing generated file (run scripts/translate_site.py)' % path)
            elif read_text(path) != expected:
                problems.append('%s: hand-edited or stale generated file' % path)
        if site.strings_misses(lang):
            log('stale: web/i18n/%s.js has %d untranslated strings' % (lang, len(site.strings_misses(lang))))
        else:
            path = os.path.join(site.web_dir, 'i18n', lang + '.js')
            if not os.path.exists(path):
                problems.append('%s: missing generated file' % path)
            elif read_text(path) != site.render_strings(lang):
                problems.append('%s: hand-edited or stale generated file' % path)
    languages_js = os.path.join(site.web_dir, 'i18n', 'languages.js')
    if not os.path.exists(languages_js) or read_text(languages_js) != site.render_languages_js(languages):
        problems.append('%s: does not match the languages that are available' % languages_js)
    for page in site.pages:
        if site.with_hreflang(page.source, page, languages) != page.source:
            problems.append('%s: the hreflang block is out of date' % page.path)
    for problem in problems:
        log('error: ' + problem)
    if problems:
        log('%d generated files differ from what the cache produces; run scripts/translate_site.py and commit the result'
            % len(problems))
        return 1
    log('OK')
    return 0


def main(argv=None, client=None):
    parser = argparse.ArgumentParser(description='Translate the info portal with DeepL (see the module docstring).')
    parser.add_argument('--languages', help='comma-separated language codes, e.g. nl,fr (default: the languages '
                                            'that have a cache in translations/)')
    parser.add_argument('--dry-run', action='store_true', help='only count what DeepL would be asked to translate')
    parser.add_argument('--check', action='store_true', help='verify the generated files against the cache')
    parser.add_argument('--sync-glossary', action='store_true', help='create or update the DeepL glossary')
    parser.add_argument('--export-review', metavar='LANG', help='write translations/review/<lang>.csv')
    parser.add_argument('--import-review', metavar='LANG', help='read translations/review/<lang>.csv back')
    parser.add_argument('--prune', action='store_true', help='remove cache entries whose English text is gone')
    parser.add_argument('--retranslate-glossary-changes', action='store_true',
                        help='send machine translations made with an older glossary again')
    parser.add_argument('--web-dir', default='web')
    parser.add_argument('--translations-dir', default='translations')
    args = parser.parse_args(argv)

    site = Site(args.web_dir, args.translations_dir)
    languages = parse_languages(args.languages) or site.cached_languages()
    log('%d pages, %d unique units (%d from the pages, %d strings, %d national descriptions)'
        % (len(site.pages), len(site.units),
           sum(1 for u in site.units.values() if u.kind != 'string'),
           sum(1 for u in site.units.values() if u.kind == 'string' and not u.path.startswith('national.descriptions.')),
           sum(1 for u in site.units.values() if u.kind == 'string' and u.path.startswith('national.descriptions.'))))

    if args.check:
        return check(site)
    if args.export_review:
        site.export_review(parse_languages(args.export_review)[0])
        return 0
    if args.import_review:
        site.import_review(parse_languages(args.import_review)[0])
        languages = [parse_languages(args.import_review)[0]]
    if args.prune:
        for lang in languages:
            site.prune(lang)
        return 0

    key = os.environ.get('DEEPL_AUTH_KEY', '').strip()
    if client is None and key and not args.dry_run:
        client = DeepLClient(key)
    if args.sync_glossary:
        if client is None:
            raise SystemExit('--sync-glossary needs DEEPL_AUTH_KEY')
        site.sync_glossary(client)

    total_missing = 0
    ready = []
    for lang in languages:
        misses = site.misses(lang, args.retranslate_glossary_changes)
        characters = sum(len(unit.source) for unit in misses)
        if args.dry_run:
            log('%s: %d untranslated units, %d characters would be sent to DeepL' % (lang, len(misses), characters))
            total_missing += characters
            continue
        if misses and client is not None:
            billed = site.translate(lang, client, misses)
            log('%s: %d characters billed' % (lang, billed))
            misses = site.misses(lang)
        if misses:
            log('%s: %s has %d untranslated units (%d characters); its pages are left as they are. '
                'Visitors can translate the English pages with their browser (see README)'
                % ('DEEPL_AUTH_KEY is not set' if client is None else 'not everything could be translated',
                   lang, len(misses), sum(len(unit.source) for unit in misses)))
            continue
        ready.append(lang)

    if args.dry_run:
        log('total: %d characters' % total_missing)
        return 0

    # The languages the portal is available in after this run: those written now and those whose
    # complete tree already exists; every page lists all of them in its hreflang links
    listed = sorted(set(ready) | set(site.listed_languages()))
    for lang in ready:
        site.write_tree(lang, listed)
        log('%s: pages written to %s' % (lang, site.tree_dir(lang)))
    site.write_shared(listed)
    log('available languages: ' + ', '.join(['en'] + listed))
    if client is not None:
        try:
            usage = client.usage()
            log('DeepL usage: %s of %s characters' % (usage.get('character_count'), usage.get('character_limit')))
        except DeepLError as error:
            log('warning: could not read the DeepL usage: %s' % error)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (DeepLError, ValueError) as error:
        log('error: %s' % error)
        sys.exit(1)
