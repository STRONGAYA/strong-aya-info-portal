"""
Translate the STRONG-AYA info portal with DeepL, at build time (see "Languages" in README.md).

English is the only hand-edited source: the 17 pages in web/ (web/*.html and web/module_*/*.html) and
the text that the scripts generate (web/i18n/en.js). This script

- cuts the pages into translation units (the inner HTML of a heading, paragraph, button, list item...,
  and the alt, aria-label, title, placeholder and data-tooltip attributes), the strings file into its
  string values, and takes the one-sentence descriptions of the national websites
  (web/data/national_resources.json) as units too;
- translates the units a language does not have yet with the DeepL API (DEEPL_AUTH_KEY in the environment)
  and keeps every translation in translations/<lang>.json, keyed by the SHA-256 of the English text, so
  that unchanged text is never sent or billed again and reviewers can correct a translation in one place;
- writes one static page tree per language (web/<lang>/..., same paths as the English pages) plus
  web/i18n/<lang>.js (with the national descriptions under national.descriptions, keyed "<country>/<index>",
  which portal.js prefers over the English ones in the shared data file), and keeps web/i18n/languages.js
  and the hreflang links of the English pages up to date.

Without a key the script regenerates the trees from the cache; a language with untranslated text is left
as it is (visitors can then translate the English pages with their browser, see README.md).

Usage (from the repository root):

    python scripts/translate_site.py --languages nl --dry-run   # what DeepL would bill, nothing written
    python scripts/translate_site.py --languages nl             # translate the misses and write the tree
    python scripts/translate_site.py                            # every language with a cache
    python scripts/translate_site.py --check                    # generated output matches the cache (CI)
    python scripts/translate_site.py --sync-glossary            # translations/glossary.tsv -> DeepL
    python scripts/translate_site.py --export-review nl         # translations/review/nl.csv for a reviewer
    python scripts/translate_site.py --import-review nl         # ... and back into the cache
    python scripts/translate_site.py --prune                    # drop cache entries whose English text is gone

Standard library only.
"""
