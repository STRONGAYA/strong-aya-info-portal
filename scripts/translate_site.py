def load_glossary(path):
    """The rows of the glossary TSV: 'en' and one column per language (plus '*' for every language)."""
    if not os.path.exists(path):
        return [], []
    with open(path, 'r', encoding='utf-8', newline='') as f:
        rows = list(csv.reader(f, delimiter='\t'))
    rows = [row for row in rows if any(cell.strip() for cell in row)]
    if not rows:
        return [], []
    header = [cell.strip() for cell in rows[0]]
    entries = [dict(zip(header, [cell.strip() for cell in row])) for row in rows[1:]]
    return header, entries


def glossary_entries(header, rows, lang):
    """(term, translation) pairs for a language: its own cell, else the '*' cell, else nothing."""
    if lang not in header:
        return []
    pairs = []
    for row in rows:
        term = row.get('en', '')
        translation = row.get(lang, '') or row.get('*', '')
        if term and translation:
            pairs.append((term, translation))
    return pairs


def glossary_version(path):
    if not os.path.exists(path):
        return None
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()[:12]


